//===========================================================================
// 模块名   : vpp_mv
// 功能     : 把 ADC 的 Vpp 原始计数(LSB) 换算成电压(mV)
//
// 为什么要单独一个模块:
//   换算公式里有一个 8x16 乘法 + 饱和判断。放在 measure_report 里会跟
//   字符生成的长组合链串在一起, 50MHz 下有建立时间风险, 也没法单独验。
//   拆出来以后: ①输入输出都对着寄存器, 组合链短; ②可以单独写仿真testbench。
//
// 换算公式:
//     mv = vpp_lsb * KN >> 10                结果饱和到 9999mV
//   其中 KN = 每 LSB 对应多少 mV, 放大 1024 倍后取整(Q10 定标)。
//        例: 7.8125 mV/LSB -> KN = 8000
//        用 Q10 而不是直接存整数, 是为了不丢小数(7.8125 存不下整数)。
//
// 【为什么没有"零点偏置"这一项 —— 这是刻意去掉的, 不是漏了】
//   Vpp 的定义是"最大值 - 最小值", 是一个**差分(峰峰值)量**。
//   信号整体抬高/压低(直流偏置)时, max 和 min 同时平移, 相减立刻抵消。
//   所以 Vpp 的换算里**不存在**直流偏置项, 只有增益 KN 一个待标定量。
//   反过来, 如果硬塞一个 off 进去减, 就等于把一个本来无关的直流分量
//   当成误差扣掉, 会把读数系统性做小 —— 那是引入错误, 不是校准。
//   (将来若要显示 Vmax/Vmin/平均值这类**绝对值**, 那时才需要 off,
//    届时应另开模块处理, 不要动这里。)
//
// 全量程参考: 256 LSB x KN/1024 = 满量程 mV。
//   KN=8000 时 256 x 7.8125 = 2000mV = 2.0V 满量程(AD9280 常见 0~2V 配置)。
//   **但这只是默认假设值, 必须用万用表两点法实测标定后改**(见 0x8C 命令)。
//
// 【调试技巧: 把 KN 设成 1024 就变回"原始 LSB 显示"】
//   因为 1024 >> 10 = 1, 此时 mv = vpp_lsb x 1, V 字段打印的就是原始计数。
//   标定流程正好用它: 先发 KN=1024 读原始值, 再算真 KN 发回去。
//
// 作者     : WaveCore 队长 | 日期: 2026-09-30 | 版本: v1.1
//===========================================================================

module vpp_mv (
    input  wire [7:0]  vpp_lsb,   // 抗噪后的 Vpp 原始计数(0~255)
    input  wire [15:0] kn,        // 每 LSB 多少 mV, x1024 (Q10 定标); 1024=原始LSB模式
    output wire [13:0] mv         // 换算结果 mV, 饱和到 0~9999
);

    // 8bit x 16bit 最大 255 x 65535 = 16_711_425 < 2^24, 24 位装得下
    wire [23:0] mul = vpp_lsb * kn;

    // 右移 10 位 = 除以 1024, 还原 Q10 定标
    wire [23:0] q   = mul >> 10;

    // KN=65535 的极端值下 q 可达 16319mV, 显示只有 4 位, 超了饱和到 9999
    assign mv = (q > 24'd9999) ? 14'd9999 : q[13:0];

endmodule
