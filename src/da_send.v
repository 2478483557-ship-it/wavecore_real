//===========================================================================
// 模块名   : da_send
// 功能     : DAC 接口 - 把正弦样点按 AD9708 需要的时序送出去
// 时序讲解 : AD9708 在 da_clk 的"上升沿"锁存数据。
//            我们的样点(sine_in)来自组合逻辑查表, 在 clk 上升沿之后
//            才变化。若直接把 clk 给 DAC, DAC 锁存那一刻正好撞上数据
//            切换, 可能采到乱码。
//            解法(官方例程同款): 时钟反相再送 DAC:
//            da_clk = ~clk, 则 DAC 在 clk 的下降沿锁存,
//            那时数据已经稳定了整整半个周期, 万无一失。
// 作者     : WaveCore 队长 | 日期: 2026-09-03 | 版本: v1.0
//===========================================================================

module da_send (
    input  wire        clk,      // 系统时钟 50MHz
    input  wire [7:0]  sine_in,  // 正弦样点(组合逻辑查表输出 0~255)
    output wire        da_clk,   // DAC 锁存时钟 (管脚 B20)
    output wire [7:0]  da_data   // DAC 数据总线 (管脚 C19~C13)
);

    assign da_clk  = ~clk;       // 关键时序: 反相时钟, 让 DAC 在数据稳定期锁存
    assign da_data = sine_in;    // 样点直接送出 (AD9708 是 8bit 并行 DAC)

endmodule
