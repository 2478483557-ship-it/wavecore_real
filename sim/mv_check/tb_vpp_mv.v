//===========================================================================
// tb_vpp_mv —— vpp_mv(LSB -> mV) 纯单元测试
//
// 用法: bash run_mv_check.sh   (脚本会先同步 ../../src/vpp_mv.v)
//
// 为什么要单独测它:
//   这个模块只有 3 行, 但它决定了"电压读数对不对"。乘法写错、移位写错、
//   饱和边界写错, 都会在整帧仿真里表现为"数字不对"却很难定位。
//   这里用**硬编码的期望值**(不用同一个公式现算), 才能真的验出问题。
//
// 期望值怎么来的(手算 + Python 交叉核对):
//   mv = floor(vpp_lsb * KN / 1024)          —— 注意是**截断**, 不是四舍五入
//
//   lsb=  0, KN= 8000 ->        0 / 1024 =        0
//   lsb=139, KN= 8000 -> 1112000 / 1024 =  1085.94 -> 1085
//   lsb=255, KN= 8000 -> 2040000 / 1024 =  1992.19 -> 1992
//   lsb=139, KN= 1024 ->   142336 / 1024 =      139   <- KN=1024 就是"原始 LSB 模式"
//   lsb=255, KN= 1024 ->   261120 / 1024 =      255
//   lsb=200, KN=20000 ->  4000000 / 1024 =  3906.25 -> 3906
//   lsb=255, KN=65535 -> 16711425 / 1024 = 16319.75 -> 9999 (饱和, 原始值 16319)
//
// 关于"截断 vs 四舍五入":
//   截断带来的最大误差 < 1mV, 而 KN 本身在没标定前就有 ±5% 不确定度,
//   所以这里刻意不做 +512 的舍入(省一个 24 位加法器, LUT 已经很紧)。
//
// 作者     : WaveCore 队长 | 日期: 2026-09-30
//===========================================================================
`timescale 1ns / 1ps

module tb_vpp_mv;

    reg  [7:0]  lsb;
    reg  [15:0] kn;
    wire [13:0] mv;

    vpp_mv dut (.vpp_lsb(lsb), .kn(kn), .mv(mv));

    integer fail = 0;

    task chk(input [7:0] l, input [15:0] k, input [13:0] exp);
        begin
            lsb = l; kn = k; #10;
            if (mv === exp)
                $display("[PASS] lsb=%3d KN=%5d -> %4d mV", l, k, mv);
            else begin
                fail = fail + 1;
                $display("[FAIL] lsb=%3d KN=%5d -> %4d mV  (期望 %4d)", l, k, mv, exp);
            end
        end
    endtask

    initial begin
        $display("====== tb_vpp_mv: LSB -> mV 换算单元测试 ======");
        lsb = 8'd0; kn = 16'd8000;

        // ---- 默认标定 7.8125 mV/LSB ----
        chk(8'd0,   16'd8000, 14'd0);
        chk(8'd139, 16'd8000, 14'd1085);   // 正弦自测 Vpp 典型值
        chk(8'd111, 16'd8000, 14'd867);    // 方波自测 Vpp 典型值: 111*8000/1024=867.19
        chk(8'd255, 16'd8000, 14'd1992);

        // ---- KN=1024: 原始 LSB 透传模式(标定用) ----
        chk(8'd139, 16'd1024, 14'd139);
        chk(8'd255, 16'd1024, 14'd255);
        chk(8'd1,  16'd1024, 14'd1);

        // ---- 别的标定档位 ----
        chk(8'd200, 16'd20000, 14'd3906);  // 19.53 mV/LSB
        chk(8'd100, 16'd512,  14'd50);     //  0.5 mV/LSB(衰减探头)

        // ---- 饱和边界 ----
        chk(8'd255, 16'd65535, 14'd9999);  // 原始 16319 -> 饱和
        chk(8'd255, 16'd0,     14'd0);     // KN=0 -> 全 0(不应出现异常值)

        if (fail == 0)
            $display(">>>>>> tb_vpp_mv 全部通过 <<<<<<");
        else
            $display(">>>>>> tb_vpp_mv 有 %0d 项失败 <<<<<<", fail);
        $finish;
    end

endmodule
